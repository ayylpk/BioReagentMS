/** 归一化用：小写 + 去空白 + 去常见中英标点/括号，避免"成分 / 组成信息（Composition）"这类写法漏配 */
const norm = (s: string) => s.toLowerCase().replace(/[\s/、（）()【】[\],，。.：:;；'"]/g, '')

/** 带编号写法："第5节" / "第 5 部分" / "5. 消防措施" / "16、其他信息" */
function sectionByNumber(s: string): string | undefined {
	// 只认行首的 1~2 位分节号，且后面必须跟节/部分字样或 . 、 : 之一
	// （"7664-93-9"、"1,2-二氯乙烷"、"2024.01" 都会因不满足而被拒）
	const m = s.match(/^第\s*(\d{1,2})\s*[节部分]*/) ?? s.match(/^(\d{1,2})\s*[.、:：]\s*\S/)
	if (!m) return undefined
	const n = Number(m[1])
	return n >= 1 && n <= SDS_SECTIONS.length ? SDS_SECTIONS[n - 1] : undefined
}

/** 分节名归一化：口语别名/带编号/中英混写 → 标准 16 分节名；认不出返回 undefined（不瞎猜） */
export function normalizeSection(input: string): string | undefined {
	const raw = input?.trim()
	if (!raw) return undefined

	// ① 带编号："第5节" / "5. 消防措施"
	const byNum = sectionByNumber(raw)
	if (byNum) return byNum

	const n = norm(raw)

	// ② 直接写了标准名（含中英混写"消防措施（Fire-fighting）"；"成分组成信息"缺斜杠也能中）
	for (const std of SDS_SECTIONS) {
		const nn = norm(std)
		if (n === nn || n.includes(nn)) return std
	}

	// ③ 口语别名
	for (const [alias, std] of SECTION_ALIASES) if (n.includes(norm(alias))) return std

	return undefined
}
